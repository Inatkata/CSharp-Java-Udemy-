/* Variable/Data Types:
    - int       => Integer (whole number)
    - double    => Double-precision floating-point (number w/ decimal)
    - char      => Single character
    - string    => String of characters
    - bool      => Boolean (true/false)
*/
string hello = "Hello, world!";
int a = 12;
double pi = 3.14;
char c = 'c';
Console.WriteLine(hello);
Console.Write(a);
Console.WriteLine(" " + pi + " " + c);
short f = 2; 
long g = 15_000_000l; // extra large numbers
float d = 0.85f;    //large numbers
decimal e = 19.99m; // money
byte h = 0x10;      //up to 256
Console.WriteLine(f + " " + g + " " + d + " " + e + " " + h);



